-- ─────────────────────────────────────────────────────────────────────────────
-- STRATEGY NOTE:
-- Files are NEVER stored as binary in the database.
-- The database stores ONLY the storage path (string), e.g.:
--   dim_employee.foto_url = 'avatars/{tenant_id}/{eid}/avatar.jpg'
--   dim_employee.contract_path = 'legal-docs/{tenant_id}/{eid}/contract.pdf'
--
-- Retrieval pattern for private files:
--   1. Read the path from dim_employee / dim_tenant.
--   2. Call StorageService.getSignedUrl(bucket, path) → returns a temporary URL (1 hour).
--   3. Present the signed URL to the client for download/display.
