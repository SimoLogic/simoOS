-- ─── 2. RLS Policies: avatars (Public Bucket) ──────────────────────────────────
-- Anyone can view public avatars (they are for display).
-- Upload requires authenticated user, path must match {tenant_id}/{eid}/ pattern.

CREATE POLICY "Avatar public read"
  ON storage.objects FOR SELECT
  USING (bucket_id = 'avatars');

CREATE POLICY "Avatar authenticated upload"
  ON storage.objects FOR INSERT
  WITH CHECK (
    bucket_id = 'avatars'
    AND auth.role() = 'authenticated'
  );

CREATE POLICY "Avatar owner delete"
  ON storage.objects FOR DELETE
  USING (
    bucket_id = 'avatars'
    AND auth.role() = 'authenticated'
  );

-- ─── 3. RLS Policies: legal-docs (Private Bucket) ─────────────────────────────
-- Authenticated users can upload under their tenant's folder.
-- Read is restricted — must use Signed URL generated by the API service.
-- Principle: DB stores the path only; the signed URL is generated per-request with expiry.

